function toRad(deg: number): number {
  return (deg * Math.PI) / 180;
}

function toDeg(rad: number): number {
  return (rad * 180) / Math.PI;
}

function formatHourMinuteBn(hoursFloat: number): string {
  const normalized = ((hoursFloat % 24) + 24) % 24;
  const h24 = Math.floor(normalized);
  const mins = Math.round((normalized - h24) * 60) % 60;
  const adjH24 = Math.round((normalized - h24) * 60) >= 60 ? (h24 + 1) % 24 : h24;
  const period = adjH24 >= 12 ? 'PM' : 'AM';
  const h12 = adjH24 % 12 === 0 ? 12 : adjH24 % 12;
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${pad(h12)}:${pad(mins)} ${period}`;
}

/**
 * Astronomical solar position prayer calculator (Karachi / Islamic Foundation BD style:
 * Fajr 18 deg, Isha 18 deg, Hanafi Asr shadow = 2x). Works offline cleanly for all BD divisions.
 */
export function computeBangladeshPrayerTimes(city: BdPrayerCity, date: Date = new Date()) {
  const year = date.getFullYear();
  const startOfYear = new Date(year, 0, 1);
  const dayOfYear = Math.floor((date.getTime() - startOfYear.getTime()) / 86_400_000) + 1;
  const tzOffset = 6; // Bangladesh Standard Time (UTC+6)

  const gamma = ((2 * Math.PI) / 365) * (dayOfYear - 1);
  const eqTime =
    229.18 *
    (0.000075 +
      0.001868 * Math.cos(gamma) -
      0.032077 * Math.sin(gamma) -
      0.014615 * Math.cos(2 * gamma) -
      0.040849 * Math.sin(2 * gamma));

  const decl =
    0.006918 -
    0.399912 * Math.cos(gamma) +
    0.070257 * Math.sin(gamma) -
    0.006758 * Math.cos(2 * gamma) +
    0.000907 * Math.sin(2 * gamma) -
    0.002697 * Math.cos(3 * gamma) +
    0.00148 * Math.sin(3 * gamma);

  const solarNoon = 12 + tzOffset - city.lng / 15 - eqTime / 60;
  const latRad = toRad(city.lat);

  const hourAngleForElevation = (angleDeg: number) => {
    const cosH =
      (Math.sin(toRad(angleDeg)) - Math.sin(latRad) * Math.sin(decl)) /
      (Math.cos(latRad) * Math.cos(decl));
    const clamped = Math.max(-1, Math.min(1, cosH));
    return toDeg(Math.acos(clamped)) / 15;
  };

  const fajrDelta = hourAngleForElevation(-18);
  const sunriseDelta = hourAngleForElevation(-0.833);
  const ishaDelta = hourAngleForElevation(-18);

  // Hanafi Asr (shadow factor = 2)
  const asrAngleDeg = toDeg(Math.atan(1 / (2 + Math.tan(Math.abs(latRad - decl)))));
  const asrDelta = hourAngleForElevation(asrAngleDeg);

  const fajr = solarNoon - fajrDelta;
  const sunrise = solarNoon - sunriseDelta;
  const dhuhr = solarNoon + 2 / 60; // +2 min safety after zenith
  const asr = solarNoon + asrDelta;
  const maghrib = solarNoon + sunriseDelta + 2 / 60;
  const isha = solarNoon + ishaDelta;
  const sehriEnd = fajr - 3 / 60;

  return {
    sehriEnd: formatHourMinuteBn(sehriEnd),
    fajr: formatHourMinuteBn(fajr),
    sunrise: formatHourMinuteBn(sunrise),
    dhuhr: formatHourMinuteBn(dhuhr),
    asr: formatHourMinuteBn(asr),
    maghrib: formatHourMinuteBn(maghrib),
    isha: formatHourMinuteBn(isha),
  };
}
